/**
 * Filter cities given a search prefix or initial letters.
 * Matches initials first (e.g. 'b' -> Bengaluru, Bhopal, Bhubaneswar...), then substring.
 */
export function searchCities(query: string, limit = 12): CityData[] {
  const q = query.trim().toLowerCase()
  if (!q) return []

  // 1. Exact initial / prefix matches
  const prefixMatches = INDIAN_CITIES.filter((c) => c.city.toLowerCase().startsWith(q))
  if (prefixMatches.length >= limit) {
    return prefixMatches.slice(0, limit)
  }

  // 2. Substring matches for city or state
  const otherMatches = INDIAN_CITIES.filter(
    (c) => !c.city.toLowerCase().startsWith(q) && (c.city.toLowerCase().includes(q) || c.state.toLowerCase().startsWith(q))
  )

  return [...prefixMatches, ...otherMatches].slice(0, limit)
}

